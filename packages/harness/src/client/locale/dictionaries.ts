// The HimaHarness client's own locale dictionaries, registered once into the DSH shell's locale
// runtime (`@deepseek-ai/dsh-client-locale`) under this package's own namespace. The shell already
// ships a zh/en runtime and a Language row in Settings → General; this file only contributes the
// Hima panels' own strings in the same shape every other dsh client plugin uses (one namespace, one
// `{ zh, en }` pair, `{name}` placeholders), so picking 中文 switches these panels with the rest of
// the shell and English stays the default and the per-key fallback.
//
// English values are kept byte-for-byte equal to the literals they replaced: English is both the
// default locale and the fallback, so an unchanged English render keeps every test that asserts the
// old wording green, whether it runs here or in the desktop suite.
//
// Glossary (one consistent choice, applied throughout the Chinese column):
//   • Product nouns are kept in English inside Chinese text — they are the names a Hima operator
//     already reads on the product and in its docs: Campaign, Run, Pack, HimaPack, Site, HimaGuide,
//     Agent, Job, Ledger, Generation, Workshop, Loop, Budget, Goal, SSH, Markdown, SHA-256, MiB.
//   • Generic engineering nouns/verbs are translated: evidence 证据, verdict 判定, decision 决策,
//     observation 观测, blocker 阻塞, knowledge 知识, strategy 策略, readiness 就绪, install 安装,
//     review 审阅, confirm 确认, verify 校验, download 下载.
//   • Node kinds (legend): act 动作, judge 判定, explore 探索, wait 等待.
//   • Timing terms: setup 建立时间, hold 保持时间; WNS / TNS kept as-is.

