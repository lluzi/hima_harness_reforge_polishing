test('path dont_use_critical.tcl: built from the ticks, grouped by class, regenerated as they change', () => {
  const path = { id: 'critical_path_faster_cells', design: { name: 'demo_top' }, paths: [{ rows: [
    { cell: 'NAND2X1_SVT', cls: 'NAND2' }, { cell: 'INVX2_SVT', cls: 'INV' }, { cell: 'NAND2X2_SVT', cls: 'NAND2' },
  ] }] };
  const head = ['# dont_use_critical.tcl - generated by critical_path_faster_cells for design demo_top', '# scope: the setup-repair step only, then reset_dont_use'];
  assert.deepEqual(plain(INSIGHT.files.dontUseTcl(path, {})), { name: 'dont_use_critical.tcl', lines: 0,
    text: [...head, '# no cells marked yet: mark slower cells on the page to add them here', ''].join('\n') });
  const marks: Record<string, string[]> = { '0:0': ['NAND2X2_HVT', 'NAND2X1_HVT'], '0:2': ['NAND2X1_HVT', 'NAND2X1_SVT'], '0:1': [] };
  const first = INSIGHT.files.dontUseTcl(path, marks);
  assert.equal(first.lines, 2);
  assert.equal(first.text, [...head,
    '# NAND2: keep NAND2X1_SVT, NAND2X2_SVT and faster; drop 2 slower',
    'set_dont_use [get_lib_cells */NAND2X1_HVT]',
    'set_dont_use [get_lib_cells */NAND2X2_HVT]', ''].join('\n'), 'a cell in use in its class is never dropped');
  marks['0:1'] = ['INVX2_HVT'];
  marks['0:0'] = ['NAND2X2_HVT'];
  marks['0:2'] = [];
  assert.equal(INSIGHT.files.dontUseTcl(path, marks).text, [...head,
    '# INV: keep INVX2_SVT and faster; drop 1 slower',
    'set_dont_use [get_lib_cells */INVX2_HVT]',
    '# NAND2: keep NAND2X1_SVT and faster; drop 1 slower',
    'set_dont_use [get_lib_cells */NAND2X2_HVT]', ''].join('\n'));
});

