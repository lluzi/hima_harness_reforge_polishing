import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';
import vm from 'node:vm';

// The libinsight-analysis Pack's fixed insight page template. Its one executable script is run here
// with no document: it must only expose its pure functions (score and the action files) and not boot.
const templatePath = new URL('../../../packs/libinsight-analysis/page/insight-page.html', import.meta.url);
const template = readFileSync(templatePath, 'utf8');
const scripts = [...template.matchAll(/<script>([\s\S]*?)<\/script>/gu)];

type File = { name: string; text: string; lines?: number };
type Part = { key: string; name: string; weight: number; share: number; value: number | null; lost: number; rules: { index: number; id: string; points: number }[] };
interface Insight {
  score(rules: unknown[]): { overall: number | null; parts: Part[]; none: { index: number; id: string }[] };
  points(score: unknown): number;
  files: {
    derateSdc(rule: unknown, variant?: string | null): File;
    roadmapGapsCsv(rule: unknown): File;
    dontUseTcl(rule: unknown, marks: Record<string, string[]>): File;
    recharacteriseCsv(rule: unknown): File;
    redesignBrief(rule: unknown, item: unknown): File;
  };
}

const context = vm.createContext({});
vm.runInContext(scripts[0]![1]!, context);
const INSIGHT = (context as { INSIGHT: Insight }).INSIGHT;
const plain = <T>(value: T): T => JSON.parse(JSON.stringify(value)) as T;
const near = (actual: number | null, expected: number) => assert.ok(actual !== null && Math.abs(actual - expected) < 1e-9, `${String(actual)} != ${expected}`);
const rule = (id: string, dimension: string, affected: number, checked: number, weight: number) => ({ id, title: id, score: { dimension, affected, checked, weight } });

test('the template holds one data marker and one bare script that runs without a document', () => {
  assert.equal(template.split('/*INSIGHT-DATA*/').length, 2);
  assert.equal(scripts.length, 1);
  assert.ok(template.includes('<script type="application/json" id="insight-data">/*INSIGHT-DATA*/</script>'));
  assert.ok(INSIGHT && typeof INSIGHT.score === 'function');
  for (const banned of ['eval(', 'new Function', 'fetch(', 'XMLHttpRequest', 'onclick="']) assert.ok(!scripts[0]![1]!.includes(banned), banned);
});

test('score: the worked example, 50/30/20 over three scored parts', () => {
  const result = INSIGHT.score([
    rule('spikes', 'quality', 30, 1000, 6), // 3 % of 5 % → 0.6 × 6 = 3.6
    rule('gaps', 'ppa', 10, 400, 4), // 2.5 % → 0.5 × 4 = 2
    rule('vmin', 'robustness', 100, 1000, 6), // 10 % → capped at the full weight 6
  ]);
  const [quality, ppa, robustness] = result.parts;
  near(quality!.value, 96.4); near(ppa!.value, 98); near(robustness!.value, 94);
  near(result.overall, 0.5 * 96.4 + 0.3 * 98 + 0.2 * 94);
  near(result.overall, 96.4);
  assert.deepEqual(plain(quality!.rules.map(r => [r.id, Math.round(r.points * 10) / 10])), [['spikes', 3.6]]);
  near(INSIGHT.points({ dimension: 'ppa', affected: 0, checked: 0, weight: 6 }), 0);
});

test('score: dimension none never counts and a part without rules is not scored', () => {
  const withNone = INSIGHT.score([rule('spikes', 'quality', 30, 1000, 6), rule('gaps', 'ppa', 10, 400, 4), rule('path', 'none', 100, 100, 30)]);
  assert.deepEqual(plain(withNone.none.map(r => [r.index, r.id])), [[2, 'path']]);
  const robustness = withNone.parts.find(p => p.key === 'robustness')!;
  assert.equal(robustness.value, null, 'not scored');
  assert.equal(robustness.rules.length, 0);
  // renormalised over Quality and PPA: (0.5 × 96.4 + 0.3 × 98) / 0.8
  near(withNone.overall, (0.5 * 96.4 + 0.3 * 98) / 0.8);
  near(withNone.overall, 97);
  near(withNone.parts[0]!.share, 0.625);
  const onlyNone = INSIGHT.score([rule('path', 'none', 5, 10, 6)]);
  assert.equal(onlyNone.overall, null);
  assert.ok(onlyNone.parts.every(p => p.value === null));
});

test('score: a part floors at 0 and checked = 0 costs nothing', () => {
  const result = INSIGHT.score([1, 2, 3, 4, 5].map(i => rule(`q${i}`, 'quality', 50, 100, 30)).concat([rule('zero', 'ppa', 0, 0, 30)]));
  assert.equal(result.parts[0]!.value, 0);
  assert.equal(result.parts[1]!.value, 100);
  near(result.overall, (0.5 * 0 + 0.3 * 100) / 0.8);
});

