// Keep the client self-contained: the existing bundle carries the licensed font,
// with no remote font service, asset route, or additional browser dependency.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const target = new URL('../src/client/aix-font.ts', import.meta.url);
const fonts = [['Manrope.woff2', 'AIX_FONT_URL'], ['Urbanist.woff2', 'AIX_BRAND_FONT_URL']];
writeFileSync(target, '// Generated by scripts/make-ui-font.mjs from assets/fonts/.\n'
  + '// Manrope and Urbanist use SIL OFL 1.1; licenses are retained beside the fonts.\n'
  + fonts.map(([file, name]) => {
    const bytes = readFileSync(new URL(`../assets/fonts/${file}`, import.meta.url));
    return `export const ${name} = ${JSON.stringify(`data:font/woff2;base64,${bytes.toString('base64')}`)};\n`;
  }).join(''));
console.log(`ui fonts: ${fileURLToPath(target)}`);
