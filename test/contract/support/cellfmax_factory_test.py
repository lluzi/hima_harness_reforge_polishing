class LefTest(unittest.TestCase):
    def normalize(self):
        with tempfile.TemporaryDirectory() as t:
            src, mid, out = (os.path.join(t, n) for n in ("in.lef", "mid.lef", "obs"))
            Path(src).write_text(RAW_LEF)
            subprocess.run([sys.executable, str(FACTORY / "fix_lef_sky130hd.py"), src, "--inputs", "A,B",
                            "--output", "S,CO", "--vdd", "vdd", "--gnd", "gnd", "-o", mid],
                           check=True, capture_output=True)
            subprocess.run([sys.executable, str(FACTORY / "fix_lef_obs.py"), mid, "-o", out],
                           check=True, capture_output=True)
            return Path(out, "mid.lef").read_text()

    def test_normalization_multi_output(self):
        text = self.normalize()
        import re
        pins = re.findall(r"^\s*PIN\s+(\S+)", text, re.M)
        self.assertEqual(sorted(pins), ["A", "B", "CO", "S", "VGND", "VNB", "VPB", "VPWR"])
        self.assertRegex(text, r"PIN S\s+DIRECTION OUTPUT ;")
        self.assertRegex(text, r"PIN CO\s+DIRECTION OUTPUT ;")
        self.assertRegex(text, r"PIN A\s+DIRECTION INPUT ;")
        self.assertRegex(text, r"PIN VPWR\s+DIRECTION INOUT ;\s+USE POWER ;")
        self.assertNotIn("LAYER poly", text)                     # poly OBS dropped
        self.assertIn("RECT 1.50000000 0.60000000", text)        # internal OBS kept

    def test_snap_and_augment(self):
        text = fac.snap_lef_width(self.normalize(), 180)           # 3.50 -> 3.68 (8 sites)
        self.assertIn("SIZE 3.680 BY 2.72", text)
        self.assertIn("RECT 0.000 -0.240 3.680 0.240", text)
        self.assertIn("RECT 0.340 1.030 0.660 1.350", text)      # signal pin rects untouched
        by = fac.lef_added_rects({"gap_filled": [{"layer": "68/20", "rect_um": [0.66, 1.1, 0.8, 1.2]}],
                                  "min_area_added": [{"layer": "li1", "rect_um": [2.0, 2.0, 2.2, 2.3]}]})
        self.assertEqual(by, {"met1": [[0.66, 1.1, 0.8, 1.2]], "li1": [[2.0, 2.0, 2.2, 2.3]]})
        out = fac.augment_lef(text, by)
        pin_a = out[out.index("PIN A"):out.index("END A")]
        self.assertIn("RECT 0.660 1.100 0.800 1.200", pin_a)     # touches pin A -> joins pin A
        obs = out[out.index("OBS"):]
        self.assertIn("LAYER li1", obs)
        self.assertIn("RECT 2.000 2.000 2.200 2.300", obs)      # free-standing -> obstruction
        self.assertNotIn("0.660 1.100", obs)

    def test_trim_lef_rects(self):
        lef = ("  PIN Y\n    PORT\n       LAYER met1 ;\n        RECT 0.605 0.365 0.895 0.655 ;\n"
               "       LAYER li1 ;\n        RECT 0.605 0.365 0.895 0.655 ;\n    END\n  END Y\n")
        out = fac.trim_lef_rects(lef, {"met1": [[0.605, 0.36, 0.895, 0.395]]})
        self.assertIn("LAYER met1 ;\n        RECT 0.605 0.395 0.895 0.655 ;", out)
        self.assertIn("LAYER li1 ;\n        RECT 0.605 0.365 0.895 0.655 ;", out)   # other layer untouched
        # a strip that does not span the rect is ignored
        self.assertEqual(fac.trim_lef_rects(lef, {"met1": [[0.7, 0.36, 0.8, 0.395]]}), lef)


