class PinAccessLefTest(unittest.TestCase):
    def test_absorb_pin_obs(self):
        out, moved = fac.absorb_pin_obs(NOR2_LEF)
        self.assertEqual(moved, {"Y": 2})
        pin_y = out[out.index("PIN Y"):out.index("END Y")]
        self.assertIn("RECT 0.320 0.655 0.395 0.710", pin_y)       # touches Y's port edge
        self.assertIn("RECT 0.250 0.600 0.320 0.700", pin_y)       # overlaps Y
        obs = out[out.index(" OBS"):]
        self.assertIn("RECT 1.105 2.405 1.395 2.480", obs)        # touches only the VPWR rail: stays
        self.assertIn("LAYER li1", obs)                             # other layer: stays
        self.assertNotIn("0.320 0.655", obs)
        self.assertEqual(fac.absorb_pin_obs(out), (out, {}))       # idempotent
        self.assertEqual(sorted(pa.parse_lef_macros(out)["C_NOR2_NDB2"]["pins"]), ["A", "VPWR", "Y"])

    def test_absorb_leaves_rect_touching_two_pins(self):
        lef = NOR2_LEF.replace("RECT 0.250 0.600 0.320 0.700", "RECT 0.300 0.850 0.400 1.045")
        out, moved = fac.absorb_pin_obs(lef)
        self.assertEqual(moved, {"Y": 1})
        self.assertIn("RECT 0.300 0.850 0.400 1.045", out[out.index(" OBS"):])

    def test_profiles_and_rank(self):
        self.assertIn("tech_m1_overrides.py", fac.PROFILES["strict-m1"])
        self.assertEqual(fac.DEFAULT_PROFILES.split(",")[:2], ["strict-m1", "relaxed-m1"])
        ok = {k: {"ok": True} for k in fac.STAGES}
        bad_pa = dict(ok, pinaccess={"ok": False, "noAccess": ["A2"]}, drc={"ok": True, "count": 0})
        dirty = dict(ok, drc={"ok": False, "count": 3}, pinaccess={"ok": True})
        self.assertEqual(fac.attempt_rank(ok)[0], 0)
        self.assertEqual(fac.attempt_rank(bad_pa)[0], 1)              # pin access gates clean
        self.assertLess(fac.attempt_rank(bad_pa), fac.attempt_rank(dirty))
        self.assertEqual(fac.classify_failure("pinaccess", "no access point: A2"), "pinaccess:no-access-point")


class PinAccessCheckTest(unittest.TestCase):
    MACROS = {"C": {"size": (1.84, 2.72), "pins": {"A": {"use": "SIGNAL"}, "Y": {"use": "SIGNAL"},
                                                   "VPWR": {"use": "POWER"}}},
              "nb": {"size": (0.92, 2.72), "pins": {"B": {"use": "SIGNAL"}}}}

    def test_parse_and_site(self):
        m = pa.parse_lef_macros(NOR2_LEF)["C_NOR2_NDB2"]
        self.assertEqual(m["size"], (2.3, 2.72))
        self.assertEqual(pa.signal_pins(m), ["Y", "A"])
        self.assertEqual(pa.parse_site("SITE unithd\n  SIZE 0.46 BY 2.72 ;\nEND unithd\n", "unithd"), (0.46, 2.72))

    def test_def_rows_orients_and_skip(self):
        rows = pa.copy_rows(("N", "FS"), True)
        self.assertEqual(pa.copies(rows), ["N0", "FS0", "N1", "FN2", "N3", "FS1", "S2", "FS3"])
        d = pa.build_def(["C"], self.MACROS, "unithd", (0.46, 2.72), skip={"C": {"A"}}, rows_plan=rows,
                         neighbors=["nb"])
        self.assertIn("- C__N0 C + PLACED ( 1840 5440 ) N ;", d)
        self.assertIn("- C__FS0 C + PLACED ( 1840 8160 ) FS ;", d)
        # abutted: foundry | N | FN | N | foundry, no gaps, FS rows on odd rows
        self.assertIn("- nbr1 nb + PLACED ( 1840 10880 ) N ;", d)
        self.assertIn("- C__N1 C + PLACED ( 2760 10880 ) N ;", d)
        self.assertIn("- C__FN2 C + PLACED ( 4600 10880 ) FN ;", d)
        self.assertIn("- nbr2 nb + PLACED ( 8280 10880 ) FN ;", d)
        self.assertIn("- C__S2 C + PLACED ( 4600 13600 ) S ;", d)
        self.assertIn("ROW ROW_5 unithd 0 13600 FS", d)
        self.assertNotIn("C__N0 A )", d)                              # skipped pin: no net
        self.assertIn("( PIN io0 ) ( C__N0 Y )", d)
        self.assertIn("( nbr1 B )", d)                                # neighbours are connected too
        self.assertIn("PLACED ( 150 340 ) N", d)                      # IO on the met3 track

    def test_verdicts(self):
        rows = pa.copy_rows(("N", "FS"), False)
        log = "[ERROR DRT-0073] No access point for C__N0/A (C).\n[ERROR DRT-0073] No access point for nbr1/B (nb).\n"
        self.assertEqual(pa.no_access_pairs({"noAccess": [["C__FS0", "A"]]}, log),
                         {("C", "A", "N0"), ("C", "A", "FS0")})
        done = {"ok": True, "accessPoints": {"C/Y": 6, "C/A": 4},
                "insts": {"C__N0": {"pinAccessIdx": 0, "pins": {"Y": 1, "A": 1}},
                          "C__FS0": {"pinAccessIdx": 1, "pins": {"Y": 1, "A": 1}}}}
        ok = pa.cell_verdict("C", self.MACROS, done, set(), rows)
        self.assertEqual((ok["ok"], ok["uniqueInstances"], ok["pins"]["Y"]["perInstance"]), (True, 2, 3.0))
        weak = pa.cell_verdict("C", self.MACROS, done, set(), rows, min_ap=3)
        self.assertEqual((weak["ok"], weak["error"]), (False, "fewer than 3 access points per instance: A"))
        v = pa.cell_verdict("C", self.MACROS, done, {("A", "N0")}, rows)
        self.assertEqual((v["ok"], v["error"]), (False, "no access point: A"))
        self.assertEqual(v["pins"]["A"], {"accessPoints": 0, "perInstance": 0.0, "byCopy": {"N0": 0, "FS0": None}})
        self.assertEqual(v["pins"]["Y"]["accessPoints"], 6)


class EdgeMarginTest(unittest.TestCase):
    LEF = """MACRO X
 SIZE 1.840 BY 2.72 ;
  PIN VGND
   USE GROUND ;
    PORT
       LAYER met1 ;
        RECT 0.000 -0.240 1.840 0.240 ;
    END
  END VGND
  PIN Y
   USE SIGNAL ;
    PORT
       LAYER met1 ;
        RECT -0.020 1.725 0.270 2.015 ;
    END
  END Y
 OBS
    LAYER li1 ;
     RECT -0.085 0.535 0.415 0.785 ;
     RECT 0.000 -0.085 1.840 0.085 ;
     RECT 1.500 1.000 1.750 1.300 ;
 END
END X
"""

    def test_factory_edge_gate_and_shift(self):
        ev = fac.lef_edge_violations(self.LEF)
        self.assertEqual([(l, r[0]) for l, r in ev], [("met1", -0.02), ("li1", -0.085)])  # rail exempt
        moved = fac.shift_lef_x(self.LEF, 170)
        self.assertIn("SIZE 2.010 BY 2.72", moved)
        self.assertIn("RECT 0.000 -0.240 2.010 0.240", moved)        # rail re-anchored at 0
        self.assertIn("RECT 0.085 0.535 0.585 0.785", moved)
        self.assertIn("RECT 0.150 1.725 0.440 2.015", moved)
        snapped = fac.snap_lef_width(moved, 290)                       # 2.01 -> 2.30 (5 sites)
        self.assertIn("RECT 0.000 -0.240 2.300 0.240", snapped)
        self.assertEqual(fac.lef_edge_violations(snapped), [])
        self.assertEqual(fac.classify_failure("lef", "edge-margin: 2 rect(s) ..."), "lef:edge-margin")

    def test_check_edge_violations(self):
        m = pa.parse_lef_macros(self.LEF)["X"]
        ev = pa.edge_violations(m, {"li1": 0.17, "met1": 0.14})
        self.assertEqual(sorted(l for l, _ in ev), ["li1", "met1"])
        self.assertEqual(pa.edge_violations(m, {"met2": 0.14}), [])


