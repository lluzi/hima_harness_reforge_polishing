def cell(name, outputs, inputs=None, variant=None):
    raw = {"name": name, "outputs": outputs}
    if inputs is not None:
        raw["inputs"] = inputs
    if variant is not None:
        raw["variant"] = variant
    return fac.parse_cell(raw)


class ExpressionTest(unittest.TestCase):
    def test_precedence_matches_bool2cmos(self):
        # or < xor < and < not: A^B&C is A^(B&C); A|B^C is A|(B^C)
        t = fac.truth_table(fac.parse_expr("A^B&C"), ["A", "B", "C"])
        self.assertEqual(t, [0, 0, 0, 1, 1, 1, 1, 0])
        t = fac.truth_table(fac.parse_expr("A|B^C"), ["A", "B", "C"])
        self.assertEqual(t, [0, 1, 1, 0, 1, 1, 1, 1])

    def test_juxtaposition_postfix_and_tilde(self):
        self.assertEqual(fac.truth_table(fac.parse_expr("(A1 A2)'"), ["A1", "A2"]), [1, 1, 1, 0])
        self.assertEqual(fac.truth_table(fac.parse_expr("~A+B"), ["A", "B"]), [1, 1, 0, 1])

    def test_parse_errors(self):
        for bad in ("", "A&", "(A|B", "A $ B"):
            with self.assertRaises(fac.SpecError):
                fac.parse_expr(bad)

    def test_symmetric_groups(self):
        self.assertEqual(fac.symmetric_groups(["!(A|B|C)"], ["A", "B", "C"]), [["A", "B", "C"]])
        self.assertEqual(fac.symmetric_groups(["!((A1&A2)|B1)"], ["A1", "A2", "B1"]), [["A1", "A2"]])
        self.assertEqual(fac.symmetric_groups(["!((A0&!S)|(A1&S))"], ["A0", "A1", "S"]), [])
        # multi-output: symmetric only if symmetric in every output
        self.assertEqual(fac.symmetric_groups(["A^B", "A&B"], ["A", "B"]), [["A", "B"]])
        self.assertEqual(fac.symmetric_groups(["A^B", "A&!B"], ["A", "B"]), [])


class SpecTest(unittest.TestCase):
    def test_defaults_and_hash(self):
        c = cell("NOR2_PU2", {"Y": "!(A|B)"}, variant="PU2")
        self.assertEqual(c["inputs"], ["A", "B"])
        self.assertEqual(c["truth"]["Y"], [1, 0, 0, 0])
        self.assertEqual(c["variant"], {"pullup": {"all": 2.0}, "pulldown": {}})
        self.assertEqual(c["specHash"], cell("NOR2_PU2", {"Y": "!(A|B)"}, variant={"pullup": 2})["specHash"])
        self.assertNotEqual(c["specHash"], cell("NOR2_PU2", {"Y": "!(A|B)"}, variant="ND2")["specHash"])

    def test_variant_forms(self):
        self.assertEqual(fac.parse_variant("PU2ND1.5"), {"pullup": {"all": 2.0}, "pulldown": {"all": 1.5}})
        self.assertEqual(fac.parse_variant({"pullup": {"A": 2}}), {"pullup": {"A": 2.0}, "pulldown": {}})
        for bad in ("XX2", "PU", {"pullup": {"A": 20}}, {"pull": 2}, {"pullup": "2"}):
            with self.assertRaises(fac.SpecError):
                fac.parse_variant(bad)

    def test_cell_errors(self):
        cases = [
            {"name": "1BAD", "outputs": {"Y": "!A"}},
            {"name": "C", "outputs": {"Y": "!(A|B)"}, "inputs": ["A"]},          # undeclared B
            {"name": "C", "outputs": {"Y": "!A"}, "inputs": ["A", "B"]},         # unused B
            {"name": "C", "outputs": {"VPWR": "!A"}},                            # reserved pin
            {"name": "C", "outputs": {"A": "!A"}, "inputs": ["A"]},              # pin both ways
            {"name": "C", "outputs": {}},
        ]
        for raw in cases:
            with self.assertRaises(fac.SpecError, msg=json.dumps(raw)):
                fac.parse_cell(raw)

    def test_parse_spec_collects_errors_and_duplicates(self):
        cells, errors, jobs = fac.parse_spec({"jobs": 3, "cells": [
            {"name": "A1", "outputs": {"Y": "!A"}},
            {"name": "A1", "outputs": {"Y": "!A"}},
            {"name": "B1", "outputs": {"Y": "!(A|"}},
        ]})
        self.assertEqual([c["name"] for c in cells], ["A1"])
        self.assertEqual(len(errors), 2)
        self.assertEqual(jobs, 3)

    def test_example_specs_are_valid(self):
        for f in ("nor3_pu2.json", "batch24.json"):
            cells, errors, _ = fac.parse_spec(json.loads((FACTORY / "examples" / f).read_text()))
            self.assertEqual(errors, [], f)
            self.assertTrue(cells)


class SizingTest(unittest.TestCase):
    def setUp(self):
        self.nor3 = fac.parse_b2c_spice(NOR3_B2C)
        self.ha = fac.parse_b2c_spice(HA_B2C)

    def widths(self, net, kind):
        return sorted((d["g"], d["w"]) for d in net["devices"] if d["kind"] == kind)

    def test_parse(self):
        self.assertEqual(self.nor3["pins"], ["A", "B", "C", "Y", "VGND", "VNB", "VPB", "VPWR"])
        self.assertEqual(len(self.nor3["devices"]), 6)
        self.assertEqual(self.nor3["devices"][0]["kind"], "p")

    def test_pu2_doubles_every_pmos_as_fingers(self):
        s = fac.apply_sizing(self.nor3, fac.parse_variant("PU2"))
        self.assertEqual(self.widths(s, "p"), [("A", 1.0), ("A", 1.0), ("B", 1.0), ("B", 1.0), ("C", 1.0), ("C", 1.0)])
        self.assertEqual(self.widths(s, "n"), [("A", 0.65), ("B", 0.65), ("C", 0.65)])
        names = [d["name"] for d in s["devices"]]
        self.assertEqual(len(names), len(set(names)))

    def test_per_input_fractional_and_shrink(self):
        s = fac.apply_sizing(self.nor3, fac.parse_variant({"pullup": {"A": 1.5}, "pulldown": {"all": 0.5}}))
        self.assertEqual(self.widths(s, "p"), [("A", 0.75), ("A", 0.75), ("B", 1.0), ("C", 1.0)])
        # 0.65 * 0.5 = 0.325 < lclayout's 0.42 minimum -> one device clamped to 0.42
        self.assertEqual(self.widths(s, "n"), [("A", 0.42), ("B", 0.42), ("C", 0.42)])

    def test_gate_key_beats_all(self):
        s = fac.apply_sizing(self.nor3, fac.parse_variant({"pulldown": {"all": 2, "B": 1}}))
        self.assertEqual(self.widths(s, "n"), [("A", 0.65), ("A", 0.65), ("B", 0.65), ("C", 0.65), ("C", 0.65)])

    def test_out_key_scales_only_that_stage(self):
        s = fac.apply_sizing(self.ha, fac.parse_variant({"pullup": {"out:S": 2}}))
        pm = [(d["d"], d["g"]) for d in s["devices"] if d["kind"] == "p"]
        self.assertEqual(pm.count(("S", "n4")), 2)            # output inverter of S doubled
        self.assertEqual(pm.count(("CO", "n2")), 1)           # CO inverter untouched
        self.assertEqual(len(pm), 8)

    def test_unknown_key_rejected(self):
        with self.assertRaises(fac.SpecError):
            fac.apply_sizing(self.nor3, fac.parse_variant({"pullup": {"Q": 2}}))

    def test_switch_level_check(self):
        c = cell("NOR3_PU2", {"Y": "!(A|B|C)"}, variant="PU2")
        self.assertIsNone(fac.verify_switch_level(fac.apply_sizing(self.nor3, c["variant"]), c))
        h = cell("HA", {"S": "A^B", "CO": "A&B"}, ["A", "B"])
        self.assertIsNone(fac.verify_switch_level(self.ha, h))
        wrong = cell("HA", {"S": "!(A^B)", "CO": "A&B"}, ["A", "B"])
        self.assertIn("output S wrong", fac.verify_switch_level(self.ha, wrong))

    def test_emitters(self):
        c = cell("NOR3_PU2", {"Y": "!(A|B|C)"}, variant="PU2")
        s = fac.apply_sizing(self.nor3, c["variant"])
        src = fac.emit_source(s, c)
        self.assertIn(".subckt NOR3_PU2 A B C Y VGND VNB VPB VPWR", src)
        self.assertEqual(src.count("sky130_fd_pr__pfet_01v8_hvt w=1 l=0.15"), 6)
        lc = fac.emit_lclayout(s, c)
        self.assertIn(".subckt NOR3_PU2 A B C Y vdd gnd", lc)
        self.assertIn("M2 n1_i0 B n1_i1 vdd pmos w=1u l=0.15u", lc)
        self.assertNotIn("VPWR", lc)
        ref = fac.emit_lvs_ref(s, c)
        self.assertIn("n1_i1 C vdd VPB sky130_fd_pr__pfet_01v8_hvt", ref)
        self.assertIn("Y A gnd VNB sky130_fd_pr__nfet_01v8 w=0.65", ref)


class ToolOutputTest(unittest.TestCase):
    def test_lvs_verdicts(self):
        self.assertEqual(fac.parse_lvs_verdict("x\nFinal result: Circuits match uniquely.\n"), "match")
        self.assertEqual(fac.parse_lvs_verdict("Final result: Top level cell failed pin matching.\n"), "pin-mismatch")
        self.assertEqual(fac.parse_lvs_verdict("Final result: Circuits match uniquely with port errors.\n"),
                         "pin-mismatch")
        self.assertEqual(fac.parse_lvs_verdict("Final result: Netlists do not match.\n"), "mismatch")
        self.assertEqual(fac.parse_lvs_verdict("crash\n"), "unknown")

    def test_drc_report(self):
        xml = ("<report-database><items>"
               "<item><category>'li.5'</category><values/></item>"
               "<item><category>'li.5'</category><values/></item>"
               "<item><category>'m1.2'</category><values/></item>"
               "</items></report-database>")
        with tempfile.TemporaryDirectory() as t:
            p = os.path.join(t, "r.xml")
            Path(p).write_text(xml)
            self.assertEqual(fac.parse_drc_report(p), (3, {"li.5": 2, "m1.2": 1}))
            self.assertEqual(fac.parse_drc_report(os.path.join(t, "none.xml")), (None, {}))

    def test_normalize_extracted(self):
        c = cell("NOR2X", {"Y": "!(A|B)"})
        ext = (".subckt NOR2X GND VDD Y B A\n"
               "X0 Y A a_1_2# w_n15_256# sky130_fd_pr__pfet_01v8_hvt w=1 l=0.15\n"
               "X1 Y A GND VSUBS sky130_fd_pr__nfet_01v8 w=0.65 l=0.15\n"
               "C0 Y VSUBS 0.2f **FLOATING\n.ends\n")
        out, info = fac.normalize_extracted(ext, c)
        self.assertIn(".subckt NOR2X A B Y VGND VNB VPB VPWR", out)
        self.assertIn("X0 Y A a_1_2# VPB sky130_fd_pr__pfet_01v8_hvt", out)
        self.assertIn("X1 Y A VGND VNB", out)
        self.assertIn("C0 Y VNB 0.2f\n", out)
        self.assertEqual(info["nwellNodes"], ["w_n15_256#"])
        self.assertEqual(info["substrateNodes"], ["VSUBS"])
        self.assertEqual(info["missingPorts"], [])
        _, info = fac.normalize_extracted(ext.replace(" B A\n", " A\n"), c)
        self.assertEqual(info["missingPorts"], ["B"])

    def test_failure_classes(self):
        self.assertEqual(fac.classify_failure("drc", json.dumps({"m1.2": 2, "li.5": 1})), "drc:li.5+m1.2")
        self.assertEqual(fac.classify_failure("layout", "timeout rc=..."), "layout:timeout")
        self.assertEqual(fac.classify_failure("lvs", "pin-mismatch: Final result: x"), "lvs:pin-mismatch")
        self.assertEqual(fac.classify_failure("netlist", "bool2cmos rc=2: infeasible"), "netlist:bool2cmos")

    def test_attempt_rank_prefers_clean_then_lvs_then_fewer_drc(self):
        ok = {"ok": True}
        clean = {k: ok for k in ("layout", "postprocess", "extract", "lvs", "lef")}
        clean["drc"] = {"ok": True, "count": 0}
        lvs_ok = dict(clean, drc={"ok": False, "count": 5})
        lvs_bad = dict(clean, lvs={"ok": False}, drc={"ok": True, "count": 0})
        ranks = sorted([fac.attempt_rank(lvs_bad), fac.attempt_rank(clean), fac.attempt_rank(lvs_ok)])
        self.assertEqual(ranks[0], fac.attempt_rank(clean))
        self.assertEqual(ranks[1], fac.attempt_rank(lvs_ok))


